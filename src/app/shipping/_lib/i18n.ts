export type { SKey };
export type ST = (key: SKey, vars?: Record<string, string | number>) => string;

export function makeST(lang: Lang): ST {
  const dict: Record<SKey, string> = lang === "es" ? es : en;
  return (key, vars) => {
    let out = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
    return out;
  };
}
